# 爬虫常抓到的模板文本：同一个模板换几个词
TEMPLATE = [f"欢迎访问本站，本页面共有 {n} 条记录，点击下方按钮查看更多内容，或返回首页。" for n in (12, 37, 58, 104, 215, 9)]


def corpus():
    texts, labels, names = [], [], list(TOPICS) + ["模板"]
    for i, (name, sents) in enumerate(TOPICS.items()):
        texts += sents; labels += [i] * len(sents)
    texts += TEMPLATE; labels += [len(TOPICS)] * len(TEMPLATE)
    return texts, np.array(labels), names


def embeddings(cache=os.path.join(os.path.dirname(os.path.abspath(__file__)), "out", "sentence_embeddings.npz")):
    """返回 [n, 896] 的句向量（Qwen2.5-0.5B 最后一层 mean pooling）。第一次运行会加载模型（~1 GB，CPU 半分钟），之后读缓存。"""
    texts, labels, names = corpus()
    if os.path.exists(cache):
        return np.load(cache)["E"], texts, labels, names
    import torch
    from transformers import AutoModel, AutoTokenizer
    tok = AutoTokenizer.from_pretrained("Qwen/Qwen2.5-0.5B")
    model = AutoModel.from_pretrained("Qwen/Qwen2.5-0.5B", dtype=torch.float32).eval()
    embs = []
    with torch.no_grad():
        for i in range(0, len(texts), 16):
            batch = tok(texts[i:i + 16], return_tensors="pt", padding=True)
            h = model(**batch).last_hidden_state                          # [b, T, 896]
            m = batch["attention_mask"][..., None].float()
            embs.append(((h * m).sum(1) / m.sum(1)).numpy())               # mean pooling（只对真实 token）
    E = np.concatenate(embs)
    os.makedirs(os.path.dirname(cache), exist_ok=True)
    np.savez(cache, E=E)
    return E, texts, labels, names
